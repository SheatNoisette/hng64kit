// hng64kit-mkspriterom packs PNGs into 4bpp SP make a C header
//
// Usage: hng64kit-mkspriterom --out <sprites.bin> --header <sprites.h> <image.png>...
package main

import (
	"flag"
	"fmt"
	"image/color"
	"image/png"
	"os"
	"path/filepath"
	"strings"
)

const (
	tileDim = 16

	rowBytes  = 8
	tileBytes = tileDim * rowBytes

	maxPens     = 16
	alphaCutoff = 128

	firstPalette = 0x10
	lastPalette  = 0xFF
)

var pairByte = [rowBytes]int{7, 3, 6, 2, 5, 1, 4, 0}

type sprite struct {
	name    string
	width   int
	height  int
	pens    [tileDim][tileDim]byte
	colors  []uint32
	palette int
}

func spriteName(path string) string {
	base := strings.TrimSuffix(filepath.Base(path), filepath.Ext(path))
	name := []byte(strings.ToLower(base))

	for i, c := range name {
		if (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') {
			continue
		}

		name[i] = '_'
	}

	return string(name)
}

func loadSprite(path string) (*sprite, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	img, err := png.Decode(f)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}

	bounds := img.Bounds()
	s := &sprite{name: spriteName(path), width: bounds.Dx(), height: bounds.Dy()}

	if s.width > tileDim || s.height > tileDim {
		return nil, fmt.Errorf("%s is %dx%d, a sprite is one %dx%d tile for now", path, s.width, s.height, tileDim, tileDim)
	}

	// Pen 0 keeps a black entry so pens index colors directly
	s.colors = []uint32{0}
	lookup := map[uint32]byte{}

	for y := 0; y < s.height; y++ {
		for x := 0; x < s.width; x++ {
			c := color.NRGBAModel.Convert(img.At(bounds.Min.X+x, bounds.Min.Y+y)).(color.NRGBA)
			if c.A < alphaCutoff {
				continue
			}

			rgb := uint32(c.R)<<16 | uint32(c.G)<<8 | uint32(c.B)
			pen, ok := lookup[rgb]

			if !ok {
				if len(s.colors) == maxPens {
					return nil, fmt.Errorf("%s has more than %d colors, 4bpp holds %d", path, maxPens-1, maxPens-1)
				}

				pen = byte(len(s.colors))
				lookup[rgb] = pen
				s.colors = append(s.colors, rgb)
			}

			s.pens[y][x] = pen
		}
	}

	return s, nil
}

func encodeTile(s *sprite, out []byte) {
	for y := 0; y < tileDim; y++ {
		row := out[y*rowBytes:]

		for pair := 0; pair < rowBytes; pair++ {
			left := s.pens[y][2*pair]
			right := s.pens[y][2*pair+1]

			row[pairByte[pair]] = left<<4 | right
		}
	}
}

func buildHeader(sprites []*sprite) string {
	var b strings.Builder

	b.WriteString("// !!!!!!! Generated by hng64kit-mkspriterom, don't edit !!!!!!!\n")
	b.WriteString("#ifndef HNG64KIT_SPRITES_H\n")
	b.WriteString("#define HNG64KIT_SPRITES_H\n\n")
	b.WriteString("#include <stdint.h>\n\n")
	b.WriteString("#include <libhng64/sprite.h>\n\n")

	for tile, s := range sprites {
		fmt.Fprintf(&b, "static const uint32_t sprite_%s_colors[] = {\n", s.name)

		for _, rgb := range s.colors {
			fmt.Fprintf(&b, "    0x%08X,\n", rgb)
		}

		b.WriteString("};\n\n")

		fmt.Fprintf(&b, "static const struct hng_sprite_image sprite_%s = {\n", s.name)
		fmt.Fprintf(&b, ".tile = 0x%05X,\n", tile)
		fmt.Fprintf(&b, ".palette = 0x%02X,\n", s.palette)
		fmt.Fprintf(&b, ".width = %d,\n", s.width)
		fmt.Fprintf(&b, ".height = %d,\n", s.height)
		fmt.Fprintf(&b, ".colors = sprite_%s_colors,\n", s.name)
		fmt.Fprintf(&b, ".color_count = %d,\n", len(s.colors))
		b.WriteString("};\n\n")
	}

	b.WriteString("#endif\n")

	return b.String()
}

func buildSprites(paths []string, outPath, headerPath string) error {
	sprites := make([]*sprite, 0, len(paths))
	seen := map[string]string{}

	for i, path := range paths {
		s, err := loadSprite(path)
		if err != nil {
			return err
		}

		if other, dup := seen[s.name]; dup {
			return fmt.Errorf("%s and %s both name sprite_%s", other, path, s.name)
		}

		seen[s.name] = path

		s.palette = firstPalette + i
		if s.palette > lastPalette {
			return fmt.Errorf("%s needs palette 0x%X, only 0x%X-0x%X are free", path, s.palette, firstPalette, lastPalette)
		}

		sprites = append(sprites, s)
	}

	// Tile n sits at n * 128 so images go in order from tile 0
	sp := make([]byte, len(sprites)*tileBytes)

	for tile, s := range sprites {
		encodeTile(s, sp[tile*tileBytes:])
	}

	err := os.WriteFile(outPath, sp, 0o644)
	if err != nil {
		return err
	}

	return os.WriteFile(headerPath, []byte(buildHeader(sprites)), 0o644)
}

func main() {
	outPath := flag.String("out", "", "SP sprite image to write")
	headerPath := flag.String("header", "", "C header to write")
	flag.Parse()

	if *outPath == "" || *headerPath == "" || flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "usage: hng64kit-mkspriterom --out <sprites.bin> --header <sprites.h> <image.png>...")
		os.Exit(2)
	}

	err := buildSprites(flag.Args(), *outPath, *headerPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "hng64kit-mkspriterom:", err)
		os.Exit(1)
	}
}
